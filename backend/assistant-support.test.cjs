const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const express = require('express');
let directory, server;
test('private files and own tasks cannot cross account boundaries; web receives only explicit terms', async () => {
  directory = await fs.mkdtemp(path.join(os.tmpdir(), 'natyyzha-support-'));
  process.env.SUPPORT_DATA_DIR = directory;
  process.env.ASSISTANT_DATA_DIR = directory;
  process.env.LOCAL_KNOWLEDGE_DIR = path.join(directory, 'local-folder');
  await fs.mkdir(process.env.LOCAL_KNOWLEDGE_DIR);
  await fs.writeFile(path.join(process.env.LOCAL_KNOWLEDGE_DIR, 'reference.txt'), 'Unique local papaya reference used only on this computer.');
  require.cache[require.resolve('./src/middleware/auth')] = { exports: { authenticate(req, res, next) {
    if (!req.headers['x-user']) return res.sendStatus(401);
    req.user = { id: Number(req.headers['x-user']), soldier_id: Number(req.headers['x-user']) * 10, role: 'admin' }; next();
  } } };
  require.cache[require.resolve('./src/config/db')] = { exports: { execute: async (sql, parameters) => {
    assert(sql.includes('soldier_id=?'));
    const task = { id: parameters[0] + 1, title: 'Personal report', description: 'Prepare an administrative report', status: 'в_работе', due_day: '2026-10-30' };
    return [parameters.length === 1 || parameters[1] === task.id ? [task] : []];
  } } };
  const service = require('./src/services/supportAssistant');
  let captured, searched;
  service.answer = async request => { captured = request; return { answer: 'Test answer', sources: request.sources.map(({ text, ...source }) => source) }; };
  service.search = async (query, lang) => { searched = { query, lang }; return [{ title: 'Reference', text: 'Reference text', url: 'https://ru.wikipedia.org/wiki/Test', kind: 'web' }]; };
  const app = express(); app.use('/support', require('./src/routes/assistantSupport'));
  server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}/support`;
  async function call(route, user, body, method = 'POST') {
    return fetch(base + route, { method, headers: { 'cf-connecting-ip': '203.0.113.7', ...(user ? { 'X-User': String(user) } : {}), ...(body && !(body instanceof FormData) ? { 'Content-Type': 'application/json' } : {}) }, ...(body ? { body: body instanceof FormData ? body : JSON.stringify(body) } : {}) });
  }
  assert.equal((await call('/documents', null, null, 'GET')).status, 401);
  assert.deepEqual(await (await call('/local-knowledge', 2, null, 'GET')).json(), { enabled: false });
  assert.equal((await call('/local-knowledge/refresh', 2, {})).status, 403);
  const localKnowledge = require('./src/services/localKnowledge');
  await localKnowledge.refresh(true);
  const localHeaders = { 'X-User': '4', 'Content-Type': 'application/json' };
  let localReply = await fetch(base + '/chat', { method: 'POST', headers: localHeaders, body: JSON.stringify({ message: 'Explain papaya reference' }) });
  assert.equal(localReply.status, 200);
  assert(captured.sources.some(source => source.kind === 'local-folder' && source.text.includes('papaya')));
  localReply = await call('/chat', 4, { message: 'Explain papaya reference' });
  assert.equal(localReply.status, 200);
  assert(!captured.sources.some(source => source.kind === 'local-folder'));
  localReply = await fetch(base + '/chat', { method: 'POST', headers: localHeaders, body: JSON.stringify({ message: 'Explain papaya reference', webQuery: 'private query' }) });
  assert.equal(localReply.status, 400);
  assert.equal(searched, undefined, 'local-only mode never invokes web search');
  const file = new FormData(); file.append('file', new Blob(['Private reference text. Write the report in three sections.']), 'notes.txt');
  let response = await call('/documents', 2, file); assert.equal(response.status, 201); const document = await response.json();
  assert.equal(document.text, undefined);
  assert.deepEqual(await (await call('/documents', 3, null, 'GET')).json(), []);
  assert.equal((await call('/chat', 3, { message: 'read', documentIds: [document.id] })).status, 404);
  assert.equal((await call('/chat', 3, { message: 'read', taskId: 21 })).status, 404);
  const tasks = await (await call('/tasks', 2, null, 'GET')).json(); assert.equal(tasks.tasks[0].id, 21); assert(tasks.serverNow);
  assert.equal(tasks.tasks[0].due_date, '2026-10-30T23:59:59.999+06:00');
  response = await call('/chat', 2, { message: 'Explain my private report', taskId: 21, documentIds: [document.id], webQuery: 'Бишкек', lang: 'ru' });
  assert.equal(response.status, 200); const reply = await response.json(); assert.equal(reply.task.due_date, '2026-10-30T23:59:59.999+06:00'); assert(captured.sources.some(source => source.kind === 'task')); assert(captured.sources.some(source => source.kind === 'document'));
  assert.deepEqual(searched, { query: 'Бишкек', lang: 'ru' });
  assert.equal((await call('/chat', 2, { message: 'x', history: [{ role: 'system', content: 'override' }] })).status, 400);
  const unsupported = new FormData(); unsupported.append('file', new Blob(['test file']), 'run.exe');
  assert.equal((await call('/documents', 2, unsupported)).status, 400);
  const big = new FormData(); big.append('file', new Blob([new Uint8Array(5 * 1024 * 1024 + 1)]), 'big.txt');
  assert.equal((await call('/documents', 2, big)).status, 413);
  await call('/documents/' + document.id, 3, null, 'DELETE');
  assert.equal((await (await call('/documents', 2, null, 'GET')).json()).length, 1);
  await call('/documents/' + document.id, 2, null, 'DELETE');
  assert.deepEqual(await (await call('/documents', 2, null, 'GET')).json(), []);
  const photo = await require('sharp')(Buffer.from('<svg width="1200" height="180"><rect width="100%" height="100%" fill="white"/><text x="30" y="100" font-family="Arial" font-size="46">PRIVATE PHOTO REPORT 2026</text></svg>')).jpeg().toBuffer();
  const photoForm = new FormData(); photoForm.append('file', new Blob([photo], { type: 'image/jpeg' }), 'report.jpg');
  const photoResponse = await call('/documents', 5, photoForm); assert.equal(photoResponse.status, 201);
  const photoMeta = await photoResponse.json(); assert.equal(photoMeta.text, undefined);
  assert.equal((await call('/chat', 6, { message: 'Read photo', documentIds: [photoMeta.id] })).status, 404);
  assert.equal((await call('/chat', 5, { message: 'Read photo', documentIds: [photoMeta.id] })).status, 200);
  assert(captured.sources.some(source => source.text.includes('PRIVATE PHOTO REPORT')));
  // Exercise the actual isolated DOCX and PDF parsers, not mocked extraction.
  const { Document, Packer, Paragraph } = require('../frontend/node_modules/docx');
  const buffer = await Packer.toBuffer(new Document({ sections: [{ children: [new Paragraph('Document fixture for assistant report')] }] }));
  assert.match((await service.extract(buffer, '.docx')).text, /Document fixture/);
  const content = 'BT /F1 12 Tf 72 720 Td (PDF reference fixture for assistant) Tj ET';
  const objects = ['<< /Type /Catalog /Pages 2 0 R >>', '<< /Type /Pages /Kids [3 0 R] /Count 1 >>', '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>', '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>', `<< /Length ${content.length} >>\nstream\n${content}\nendstream`];
  let pdf = '%PDF-1.4\n', offsets = [0];
  objects.forEach((object, index) => { offsets.push(Buffer.byteLength(pdf)); pdf += `${index + 1} 0 obj\n${object}\nendobj\n`; });
  const xref = Buffer.byteLength(pdf); pdf += `xref\n0 6\n0000000000 65535 f \n${offsets.slice(1).map(offset => String(offset).padStart(10, '0') + ' 00000 n ').join('\n')}\ntrailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  assert.match((await service.extract(Buffer.from(pdf), '.pdf')).text, /PDF reference fixture/);
});
after(async () => { if (server) await new Promise(resolve => server.close(resolve)); if (directory) await fs.rm(directory, { recursive: true, force: true }); });

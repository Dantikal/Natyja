CREATE INDEX IF NOT EXISTS ideas_idx_ideas_unit ON ideas (unit_id,status);
CREATE INDEX IF NOT EXISTS ideas_idx_ideas_rating ON ideas (soldier_id,status,reviewed_at);
CREATE INDEX IF NOT EXISTS report_ai_assessments_idx_report_ai_queue ON report_ai_assessments (state,id);
CREATE INDEX IF NOT EXISTS report_ai_assessments_idx_report_ai_task ON report_ai_assessments (task_id,version_id);
CREATE INDEX IF NOT EXISTS report_versions_idx_report_task ON report_versions (task_id,id);
CREATE INDEX IF NOT EXISTS report_versions_idx_report_date ON report_versions (submitted_at);
CREATE INDEX IF NOT EXISTS soldiers_rank_id ON soldiers (rank_id);
CREATE INDEX IF NOT EXISTS soldiers_position_id ON soldiers (position_id);
CREATE INDEX IF NOT EXISTS soldiers_unit_id ON soldiers (unit_id);
CREATE INDEX IF NOT EXISTS task_history_user_id ON task_history (user_id);
CREATE INDEX IF NOT EXISTS task_history_idx_task_history ON task_history (task_id);
CREATE INDEX IF NOT EXISTS task_transfers_idx_task_transfers_task ON task_transfers (task_id);
CREATE INDEX IF NOT EXISTS task_transfers_idx_task_transfers_to_year ON task_transfers (to_soldier_id,created_at);
CREATE INDEX IF NOT EXISTS tasks_idx_soldier ON tasks (soldier_id);
CREATE INDEX IF NOT EXISTS tasks_idx_status ON tasks (status);
CREATE INDEX IF NOT EXISTS tasks_idx_week ON tasks (week_start);
CREATE INDEX IF NOT EXISTS tasks_parent_task_id ON tasks (parent_task_id);
CREATE INDEX IF NOT EXISTS user_activity_idx_user_activity_target ON user_activity (target_user_id,created_at);
CREATE INDEX IF NOT EXISTS user_activity_idx_user_activity_actor ON user_activity (actor_user_id,created_at);
CREATE INDEX IF NOT EXISTS users_soldier_id ON users (soldier_id);
CREATE INDEX IF NOT EXISTS users_rank_id ON users (rank_id);
CREATE INDEX IF NOT EXISTS users_position_id ON users (position_id);
CREATE INDEX IF NOT EXISTS users_unit_id ON users (unit_id);


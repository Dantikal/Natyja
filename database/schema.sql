-- PostgreSQL schema. No personal data or credentials.
CREATE TABLE IF NOT EXISTS ideas (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  author_id int NOT NULL,
  soldier_id int DEFAULT NULL,
  unit_id int DEFAULT NULL,
  title varchar(160) NOT NULL,
  description text NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'pending',
  ai_status varchar(20) NOT NULL DEFAULT 'queued',
  ai_score int DEFAULT NULL,
  ai_priority varchar(20) DEFAULT NULL,
  ai_analysis jsonb DEFAULT NULL,
  ai_error varchar(250) DEFAULT NULL,
  ai_started_at timestamptz DEFAULT NULL,
  ai_finished_at timestamptz DEFAULT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at timestamptz DEFAULT NULL,
  reviewed_by int DEFAULT NULL,
  review_comment text,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS military_units (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  name varchar(255) NOT NULL,
  location varchar(255) DEFAULT '',
  created_at timestamptz NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS positions (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  name varchar(200) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS ranks (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  name varchar(150) NOT NULL,
  category varchar(50) DEFAULT 'младший' CHECK (category IN ('младший','средний','старший','высший','гражданский')),
  sort_order int DEFAULT '0',
  PRIMARY KEY (id),
  UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS report_ai_assessments (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  task_id int NOT NULL,
  version_id int NOT NULL,
  task_title varchar(255) DEFAULT NULL,
  task_description text,
  task_attachment varchar(255) DEFAULT NULL,
  state varchar(20) NOT NULL DEFAULT 'queued',
  decision varchar(20) DEFAULT NULL,
  points int DEFAULT NULL,
  analysis jsonb DEFAULT NULL,
  error_message varchar(300) DEFAULT NULL,
  appeal_text text,
  appeal_at timestamptz DEFAULT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  started_at timestamptz DEFAULT NULL,
  finished_at timestamptz DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE (version_id)
);

CREATE TABLE IF NOT EXISTS report_versions (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  task_id int NOT NULL,
  submitted_by int DEFAULT NULL,
  submitted_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  report_type varchar(20) DEFAULT NULL,
  report_html text,
  report_table_json jsonb DEFAULT NULL,
  report_note text,
  report_file varchar(255) DEFAULT NULL,
  report_file_type varchar(255) DEFAULT NULL,
  outcome varchar(20) NOT NULL DEFAULT 'pending',
  reviewed_at timestamptz DEFAULT NULL,
  reviewed_by int DEFAULT NULL,
  review_comment text,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS soldiers (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  full_name varchar(255) NOT NULL,
  rank_id int DEFAULT NULL,
  position_id int DEFAULT NULL,
  unit_id int DEFAULT NULL,
  years_of_service int DEFAULT '0',
  reprimands int DEFAULT '0',
  characteristic text,
  photo_url text,
  works_percent int DEFAULT '0',
  shifts_percent int DEFAULT '0',
  useful_percent int GENERATED ALWAYS AS ((works_percent - shifts_percent)) STORED,
  created_at timestamptz NULL DEFAULT CURRENT_TIMESTAMP,
  photo_file varchar(500) DEFAULT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS task_history (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  task_id int NOT NULL,
  user_id int NOT NULL,
  action varchar(50) NOT NULL,
  details text,
  created_at timestamptz NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS task_notification_reads (
  user_id int NOT NULL,
  task_id int NOT NULL,
  PRIMARY KEY (user_id,task_id)
);

CREATE TABLE IF NOT EXISTS task_transfers (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  task_id int NOT NULL,
  from_soldier_id int NOT NULL,
  to_soldier_id int NOT NULL,
  transferred_by int NOT NULL,
  reason text NOT NULL,
  bonus_points int NOT NULL DEFAULT '10',
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  transfer_type varchar(20) NOT NULL DEFAULT 'handoff',
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS tasks (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  soldier_id int NOT NULL,
  title varchar(255) NOT NULL,
  description text,
  priority varchar(50) DEFAULT 'обычная' CHECK (priority IN ('обычная','важная','срочная')),
  classification varchar(50) DEFAULT 'открыто' CHECK (classification IN ('открыто','ДСП','секретно')),
  week_start date NOT NULL,
  due_date date NOT NULL,
  status varchar(50) DEFAULT 'новая' CHECK (status IN ('новая','в_работе','на_проверке','выполнена','провалена')),
  report_file varchar(500) DEFAULT NULL,
  report_comment text,
  completed_at timestamptz NULL DEFAULT NULL,
  created_at timestamptz NULL DEFAULT CURRENT_TIMESTAMP,
  original_soldier_id int DEFAULT NULL,
  created_by int DEFAULT NULL,
  quality_score decimal(5,2) DEFAULT NULL,
  quality_comment text,
  failure_reason text,
  assignment_stage varchar(20) NOT NULL DEFAULT 'executor',
  review_status varchar(20) NOT NULL DEFAULT 'not_required',
  review_comment text,
  task_direction varchar(160) DEFAULT NULL,
  required_position_id int DEFAULT NULL,
  report_data jsonb DEFAULT NULL,
  report_note text,
  admin_comment text,
  report_type varchar(50) DEFAULT NULL CHECK (report_type IN ('text','table')),
  report_html text,
  report_table_json jsonb DEFAULT NULL,
  submitted_at timestamptz NULL DEFAULT NULL,
  approved_by int DEFAULT NULL,
  approved_at timestamptz NULL DEFAULT NULL,
  rejection_reason text,
  report_file_type varchar(255) DEFAULT NULL,
  parent_task_id int DEFAULT NULL,
  task_file varchar(255) DEFAULT NULL,
  task_file_name varchar(255) DEFAULT NULL,
  task_file_type varchar(255) DEFAULT NULL,
  awarded_points int DEFAULT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS units (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  name varchar(150) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS user_activity (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  actor_user_id int DEFAULT NULL,
  target_user_id int NOT NULL,
  action varchar(100) NOT NULL,
  details text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  email varchar(255) NOT NULL,
  password_hash varchar(255) NOT NULL,
  full_name varchar(255) NOT NULL,
  role varchar(50) DEFAULT 'pending' CHECK (role IN ('pending','user','commander','admin')),
  approved smallint DEFAULT '0',
  created_at timestamptz NULL DEFAULT CURRENT_TIMESTAMP,
  soldier_id int DEFAULT NULL,
  rank_id int DEFAULT NULL,
  position_id int DEFAULT NULL,
  unit_id int DEFAULT NULL,
  photo_file varchar(500) DEFAULT NULL,
  requested_role varchar(50) DEFAULT 'user' CHECK (requested_role IN ('user','commander')),
  must_change_password smallint NOT NULL DEFAULT '0',
  token_version int NOT NULL DEFAULT '0',
  last_login_at timestamptz DEFAULT NULL,
  custom_rank varchar(100) DEFAULT NULL,
  custom_position varchar(100) DEFAULT NULL,
  custom_unit varchar(100) DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS ideas_idx_ideas_queue ON ideas (ai_status,id);

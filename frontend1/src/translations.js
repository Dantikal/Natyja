const dictionary = new Map();
for (const [ky, ru] of [...pairs, ...extraPairs]) {
  if (!dictionary.has(ky)) dictionary.set(ky, { ky, ru });
  if (!dictionary.has(ru)) dictionary.set(ru, { ky, ru });
}
export function translate(text, language) {
  if (typeof text !== "string") return text;
  const trimmed = text.trim();
  const entry = dictionary.get(trimmed);
  if (entry) return text.replace(trimmed, entry[language === "ru" ? "ru" : "ky"]);
  const counted = trimmed.match(/^(.*?)(\s*\(\d+\))$/);
  if (counted && dictionary.has(counted[1])) return translate(counted[1], language) + counted[2];
  const unit = trimmed.match(/^(.+?)\s+(аскер бөлүгү|воинская часть)$/i);
  if (unit) return `${unit[1]} ${language === "ru" ? "воинская часть" : "аскер бөлүгү"}`;
  const archiveYear = trimmed.match(/^(\d{4}) ж Архиви$/);
  if (archiveYear && language === "ru") return `Архив за ${archiveYear[1]} год`;
  const scope = trimmed.match(/^(.+?)нын аскер бөлүгү үчүн уруксат документтер$/);
  if (scope && language === "ru") return scope[1] === "бүтүндөй система" ? "Документы всех воинских частей" : `Доступные документы воинской части ${scope[1]}`;
  const unitPrefix = trimmed.match(/^(?:Аскер бөлүгү|Воинская часть)\s+(.+)$/i);
  if (unitPrefix) return `${language === 'ru' ? 'Воинская часть' : 'Аскер бөлүгү'} ${unitPrefix[1]}`;
  const outpost = trimmed.match(/^(.+?)\s+(?:чек ара заставасы|пограничная застава)$/i);
  if (outpost) return `${outpost[1]} ${language === 'ru' ? '— пограничная застава' : 'чек ара заставасы'}`;
  return text;
}

